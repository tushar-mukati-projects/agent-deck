import type { ITheme } from "@xterm/xterm";

import { contrast, ensureContrast } from "@/lib/contrast";

type ThemeKind = "dark" | "light";

type Ansi = [
  black: string,
  red: string,
  green: string,
  yellow: string,
  blue: string,
  magenta: string,
  cyan: string,
  white: string,
  brightBlack: string,
  brightRed: string,
  brightGreen: string,
  brightYellow: string,
  brightBlue: string,
  brightMagenta: string,
  brightCyan: string,
  brightWhite: string,
];

interface ThemeInput {
  id: string;
  name: string;
  kind: ThemeKind;
  bg: string;
  panel: string;
  elevated: string;
  hover: string;
  active: string;
  border: string;
  borderStrong: string;
  fg: string;
  muted: string;
  faint: string;
  accent: string;
  accentStrong?: string;
  onAccent: string;
  ansi: Ansi;
  terminalFg?: string;
  codeBg?: string;
  syntax?: Partial<Syntax>;
}

interface Syntax {
  comment: string;
  keyword: string;
  string: string;
  number: string;
  function: string;
  type: string;
  property: string;
  tag: string;
  variable: string;
  operator: string;
  heading: string;
  link: string;
}

export interface Theme {
  id: string;
  name: string;
  kind: ThemeKind;
  vars: Record<string, string>;
  terminal: ITheme;
  terminalContrast: number;
  swatch: [string, string, string, string];
}

